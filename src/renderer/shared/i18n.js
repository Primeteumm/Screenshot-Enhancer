  const LANGUAGES = Object.keys(STRINGS)

  // "auto": isletim sistemi dili Turkce ise Turkce, degilse Ingilizce.
  function resolve(setting, systemLocale) {
    if (LANGUAGES.includes(setting)) return setting;
    // Checks both setting and systemLocale for German
    if (/^de\b/i.test(setting || '') || /^de\b/i.test(systemLocale || '')) return 'de';
    if (/^tr\b/i.test(systemLocale || '')) return 'tr';
    return 'en';
  }


  function translate(lang, key, vars) {
    const table = STRINGS[lang] || STRINGS.tr
    let text = key in table ? table[key] : (key in STRINGS.tr ? STRINGS.tr[key] : key)
    if (vars) text = text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match))
    return text
  }

  // Sayfadaki data-i18n* isaretli ogeleri verilen dile cevirir.
  function applyToDocument(doc, lang) {
    doc.documentElement.lang = lang
    for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = translate(lang, el.dataset.i18n)
    for (const el of doc.querySelectorAll('[data-i18n-html]')) el.innerHTML = translate(lang, el.dataset.i18nHtml)
    for (const el of doc.querySelectorAll('[data-i18n-title]')) el.title = translate(lang, el.dataset.i18nTitle)
    for (const el of doc.querySelectorAll('[data-i18n-suffix]')) el.dataset.suffix = translate(lang, el.dataset.i18nSuffix)
    for (const el of doc.querySelectorAll('[data-i18n-zero]')) el.dataset.zero = translate(lang, el.dataset.i18nZero)
  }

